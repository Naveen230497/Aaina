"""Mock AI Chatbot for Aaina Legal Assistance."""

import time
import random

def get_ai_response(user_input: str) -> str:
    """A simulated AI response engine for legal questions."""
    time.sleep(1) # simulate thinking
    
    text = user_input.lower()
    
    if any(k in text for k in ["it rules", "india", "takedown"]):
        return "Under the Information Technology (Intermediary Guidelines) Rules 2021, Rule 3(2)(b), platforms in India must remove non-consensual imagery or impersonation within 24 hours of receiving a complaint. You should use the generated kit and email the platform's Grievance Officer immediately."
        
    elif any(k in text for k in ["dmca", "copyright", "us "]):
        return "The DMCA (Digital Millennium Copyright Act) is a US law. If you took the original photo, you hold the copyright. You can issue a DMCA Takedown Notice to the host demanding immediate removal. Aaina has included a pre-written DMCA draft in your kit."
        
    elif any(k in text for k in ["police", "cybercrime", "1930", "complaint", "report", "file"]):
        return "To file a formal complaint or police report regarding cybercrimes (like impersonation or harassment) in India, you can report it at https://cybercrime.gov.in or by calling the national helpline at 1930. The case file (PDF) generated by Aaina is designed to be submitted directly as digital evidence to the police."
        
    elif any(k in text for k in ["gdpr", "europe", "eu "]):
        return "Under the GDPR (Article 17), you have the 'Right to be Forgotten'. If the server is hosted in the EU, you can demand the immediate erasure of your personal data (including photos) under threat of severe regulatory fines."
        
    elif any(k in text for k in ["fake profile", "impersonat", "fake account", "stolen", "my photo"]):
        return "Impersonation is a serious crime under Section 66D of the IT Act (India). I recommend you download the 'Takedown Kit', send the provided notice to the platform's Grievance Officer, and warn your contacts using the WhatsApp card feature."
        
    else:
        responses = [
            "I am the Aaina AI Legal Assistant. I can help you understand takedown laws, jurisdictional routing, and how to file a police report.",
            "That's a great question. Remember that Aaina's case files are cryptographically signed. You should submit the PDF directly to law enforcement.",
            "I recommend using the STIX 2.1 export feature if you are working with corporate security teams.",
            "Please ensure you review all findings carefully. If a domain is hosted outside your country, the legal routing can be complex, but Aaina's Takedown Kit handles this automatically."
        ]
        return random.choice(responses)
